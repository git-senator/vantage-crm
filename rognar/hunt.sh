#!/bin/sh
# Разведка новых чатов на сервере — целиком и без присмотра.
#
# Слушатель и поисковик делят один аккаунт, поэтому на время поиска первого
# надо остановить. Делать это руками опасно: если связь оборвётся посреди
# работы (а поиск идёт десятки минут), слушатель останется лежать и никто
# этого не заметит. Здесь остановка и возврат — одна неразрывная операция,
# и возврат случится даже при ошибке поиска.
#
#   ./hunt.sh br            # искать по Бразилии
#   ./hunt.sh br es ru      # по нескольким регионам
#
# Запускать через nohup, чтобы обрыв SSH не убил процесс:
#   nohup ./hunt.sh br > hunt.log 2>&1 &
#   tail -f hunt.log

set -u
cd "$(dirname "$0")" || exit 1

REGIONS="${*:-br}"

# Что бы дальше ни случилось — слушатель должен вернуться в строй.
restore() {
    echo ""
    echo "=== возвращаю слушателя ==="
    docker compose up -d
    docker compose ps --format "{{.Name}}\t{{.Status}}"
}
trap restore EXIT INT TERM

echo "=== останавливаю слушателя (сессия нужна поиску) ==="
docker compose stop

echo ""
echo "=== пересобираю образ (код вшит внутрь, иначе запустится старый) ==="
docker compose build

echo ""
echo "=== ищу чаты: $REGIONS ==="
docker compose run --rm rognar python find.py $REGIONS
